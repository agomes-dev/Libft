#include "libft.h"

void	ft_lstclear(t_list **lst, void (*del)(void*))
{
	t_size	*current;
	t_size	*temp;

	if (lst == NULL || del == NULL)
		return ;
	current = *lst;
	while (current != NULL)
	{
		temp = current;
		current = current->next;
		del(temp->content);
		free(temp);
	}
	*lst = NULL;
}
